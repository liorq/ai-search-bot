def recovery_instructions(state: MigrationState) -> str:
    """What state the two sites are in right now, and the way out.

    The dangerous moment is a failure during `import`: the target has been
    partly overwritten, and the only correct move is a restore from the target
    backup rather than a second import attempt on top of the first.
    """
    completed = state.completed
    last = completed[-1] if completed else None
    lines = [_RECOVERY.get(last, "מצב לא מוכר — בדוק ידנית את שני האתרים.")]

    failed = state.failed_stage
    if failed:
        lines.append(f"השלב שנכשל: {failed} — {state.stage(failed).detail}")

    if failed == "import" or (last == "import" and "postcheck" not in completed):
        lines.append(
            "אזהרה: כשל בזמן ייבוא משאיר את אתר היעד במצב חלקי. "
            "שחזר מגיבוי היעד — אל תריץ ייבוא נוסף על גבי הקיים."
        )
    if not state.backups_released:
        lines.append("הגיבויים נשמרים. הם יימחקו רק באישור מפורש.")
    return "\n".join(lines)


def release_backups(state: MigrationState, confirmed: bool) -> Result:
    """Backups are only deletable after an explicit, final approval."""
    if not confirmed:
        return Result.failure(
            "not_confirmed",
            "מחיקת גיבויים דורשת אישור מפורש. עד אז הם נשארים.",
        )
    if not state.is_done("postcheck"):
        return Result.failure(
            "postcheck_incomplete",
            "בדיקות אחרי ההעברה לא הושלמו — הגיבויים נשארים.",
        )
    state.backups_released = True
    return Result.success("released", "הגיבויים סומנו כניתנים למחיקה")



@dataclass
class ToolingReport:
    """What the installed All-in-One WP Migration actually offers."""

    has_wpcli: bool = False
    has_plugin: bool = False
    subcommands: list[str] = field(default_factory=list)
    detail: str = ""

    @property
    def can_export(self) -> bool:
        return self.has_plugin and bool({"backup", "export"} & set(self.subcommands))

    @property
    def can_import(self) -> bool:
        return self.has_plugin and bool({"restore", "import"} & set(self.subcommands))

    @property
    def method(self) -> str:
        """`wp-cli` when the installed version supports it, `browser` otherwise."""
        return "wp-cli" if (self.can_export and self.can_import) else "browser"


_SUBCOMMAND = re.compile(r"^\s{2,}(?:ai1wm\s+)?([a-z][a-z0-9-]*)\s{2,}\S", re.M)


def detect_tooling(run: Runner) -> ToolingReport:
    """Ask the installed plugin what it can do, rather than assuming a version.

    The free and paid builds of All-in-One WP Migration ship different WP-CLI
    surfaces, and both have changed across releases. Parsing `wp help ai1wm` is
    the only answer that is true for the site in front of us.
    """
    report = ToolingReport()

    code, out, err = run(["wp", "--info"])
    if code != 0:
        report.detail = f"WP-CLI לא זמין: {(err or out).strip()[:120]}"
        return report
    report.has_wpcli = True

    code, out, err = run(["wp", "help", "ai1wm"])
    if code != 0:
        report.detail = (
            "WP-CLI קיים אבל All-in-One WP Migration לא חושף פקודות — "
            "נמשיך דרך ממשק הניהול"
        )
        return report

    report.has_plugin = True
    report.subcommands = sorted(set(_SUBCOMMAND.findall(out)))
    report.detail = (
        f"פקודות זמינות: {', '.join(report.subcommands)}"
        if report.subcommands else
        "wp help ai1wm רץ אבל לא הוחזרו תת-פקודות — נמשיך דרך ממשק הניהול"
    )
    return report



#  Pruning — safe categories only
# ═══════════════════════════════════════════════════════

@dataclass
class PrunePlan:
    items: list[tuple[str, int]] = field(default_factory=list)   # (category, bytes)
    refused: list[str] = field(default_factory=list)

    @property
    def savings(self) -> int:
        return sum(size for _, size in self.items)

    def render(self) -> str:
        lines = [f"  {PRUNABLE[name]}: {human(size)}" for name, size in self.items]
        if self.refused:
            lines.append("  לא נגענו: " + " · ".join(self.refused))
        return "\n".join(lines)


def plan_pruning(inventory: dict[str, int]) -> PrunePlan:
    """Decide what may be dropped from the export.

    `inventory` maps a category name to bytes. Anything not in `PRUNABLE` is
    refused by name, so an unexpected category can never be quietly swept into
    the "safe to delete" pile.
    """
    plan = PrunePlan()
    for name, size in sorted(inventory.items(), key=lambda item: -item[1]):
        if name in PRUNABLE and size > 0:
            plan.items.append((name, int(size)))
        elif name not in PRUNABLE:
            plan.refused.append(name)
    return plan


def size_gate(archive_bytes: int, limits: ServerLimits, largest: list[tuple[str, int]] | None = None) -> Result:
    """The hard stop. Measured on the finished archive, never on an estimate."""
    verdict = check_archive(archive_bytes, limits)
    if verdict:
        return verdict

    breakdown = ""
    if largest:
        breakdown = "\n\nהקבצים הגדולים:\n" + "\n".join(
            f"  {human(size):>9}  {name}" for name, size in largest[:10]
        )

    return Result.failure(
        "archive_too_large",
        verdict.detail + breakdown + (
            "\n\nלא ממשיכים אוטומטית. האפשרויות: להעלות את המגבלות בשרת היעד, "
            "להעביר את המדיה בנפרד דרך rsync/FTP ולייצא בלי uploads, "
            "או לפצל את ההעברה. מדיה ותוכן לא נמחקים כדי להיכנס לגבול."
        ),
        recoverable=True,
        archive_bytes=archive_bytes,
        hard_limit=HARD_ARCHIVE_LIMIT,
        problems=verdict.data.get("problems", []),
    )


#: All-in-One WP Migration writes a 4377-byte header before every file
#: (255 name + 14 size + 12 mtime + 4096 path) and terminates the archive with
#: one such block of zeros. A truncated download has no terminator.
WPRESS_BLOCK = 4377

#: Below this, a `.wpress` is an error page or a failed export, not a site.
MIN_ARCHIVE_BYTES = 1024 * 1024


def verify_archive(path: Path) -> Result:
    """Structural proof that an archive is complete, before it is relied on.

    This is not a restore test — only a restore proves a restore. What it does
    prove is that the file is a `.wpress`, that it is not an error page saved
    with the wrong extension, and that it was not truncated in transfer, which
    is how most "the backup was corrupt" stories actually start.
    """
    if not path.exists():
        return Result.failure(
            "archive_missing", f"קובץ הגיבוי לא נמצא: {path}", recoverable=False
        )

    size = path.stat().st_size
    if size < MIN_ARCHIVE_BYTES:
        return Result.failure(
            "archive_too_small",
            f"הקובץ {human(size)} בלבד — זו כמעט תמיד הודעת שגיאה שנשמרה "
            "בשם .wpress ולא גיבוי",
            recoverable=False,
        )

    with open(path, "rb") as fh:
        head = fh.read(255)
        fh.seek(-WPRESS_BLOCK, 2)
        tail = fh.read(WPRESS_BLOCK)

    name = head.split(b"\x00", 1)[0]
    if not name or not all(32 <= byte < 127 for byte in name):
        return Result.failure(
            "archive_not_wpress",
            "הקובץ לא נפתח בשם קובץ תקין — כנראה אינו .wpress",
            recoverable=False,
        )

    if tail != b"\x00" * WPRESS_BLOCK:
        return Result.failure(
            "archive_truncated",
            "לקובץ חסר בלוק הסיום — הוא נקטע בהעברה. אל תייבא אותו.",
            recoverable=False,
        )

    return Result.success(
        "archive_verified",
        f"{human(size)} · מבנה תקין ולא קטוע",
        size=size, path=str(path),
    )


def largest_entries(path: Path, limit: int = 10) -> list[tuple[str, int]]:
    """The biggest files inside a `.wpress`, largest first.

    The archive is a flat sequence of 4377-byte headers each followed by its
    file body, so the whole inventory can be walked by seeking — without
    extracting anything. This is what turns "too large" into an answer.
    """
    entries: list[tuple[str, int]] = []
    try:
        with open(path, "rb") as fh:
            while True:
                header = fh.read(WPRESS_BLOCK)
                if len(header) < WPRESS_BLOCK or header == b"\x00" * WPRESS_BLOCK:
                    break
                name = header[:255].split(b"\x00", 1)[0].decode("utf-8", "replace")
                raw_size = header[255:269].split(b"\x00", 1)[0]
                prefix = header[281:].split(b"\x00", 1)[0].decode("utf-8", "replace")
                try:
                    size = int(raw_size or 0)
                except ValueError:
                    break
                entries.append((f"{prefix}/{name}".lstrip("/"), size))
                fh.seek(size, 1)
    except OSError:
        return []

    return sorted(entries, key=lambda item: -item[1])[:limit]


def verify_backup_pair(source: Result, target: Result) -> Result:
    """Both backups must be provably restorable before the import is allowed."""
    failures = []
    if not source:
        failures.append(f"גיבוי המקור: {source.detail}")
    if not target:
        failures.append(f"גיבוי היעד: {target.detail}")

    if failures:
        return Result.failure(
            "backups_unverified",
            "אי אפשר להתחיל ייבוא:\n  - " + "\n  - ".join(failures)
            + "\nגיבוי שלא נבדק הוא לא גיבוי.",
            recoverable=False,
            failures=failures,
        )
    return Result.success("backups_verified", "שני הגיבויים אומתו כשחזוריים")



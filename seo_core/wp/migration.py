@dataclass
class StageState:
    name: str
    status: str = "pending"          # pending · done · failed · skipped
    detail: str = ""
    at: str = ""


@dataclass
class MigrationState:
    migration_id: str
    source: str
    target: str
    stages: dict[str, StageState] = field(default_factory=dict)
    archive_path: str = ""
    archive_bytes: int = 0
    method: str = ""
    import_approved: bool = False
    backups_released: bool = False
    created_at: str = ""

    @classmethod
    def new(cls, migration_id: str, source: str, target: str) -> "MigrationState":
        return cls(
            migration_id=migration_id, source=source, target=target,
            stages={name: StageState(name) for name in STAGES},
            created_at=_now(),
        )

    def stage(self, name: str) -> StageState:
        return self.stages.setdefault(name, StageState(name))

    def is_done(self, name: str) -> bool:
        return self.stage(name).status == "done"

    @property
    def completed(self) -> list[str]:
        return [name for name in STAGES if self.is_done(name)]

    @property
    def next_stage(self) -> str | None:
        return next((name for name in STAGES if not self.is_done(name)), None)

    @property
    def failed_stage(self) -> str | None:
        return next((n for n in STAGES if self.stage(n).status == "failed"), None)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def begin(state: MigrationState, name: str) -> Result:
    """Guard a stage: refuse to repeat it, refuse to run it out of order.

    Running the same migration script twice is the normal way a resumed run
    starts, so a completed stage is a skip and not an error.
    """
    if name not in STAGES:
        return Result.failure("unknown_stage", f"שלב לא מוכר: {name}")
    if state.is_done(name):
        return Result.failure(
            "already_done",
            f"שלב {name} כבר הושלם ב-{state.stage(name).at} — מדלג",
            recoverable=True,
        )

    position = STAGES.index(name)
    missing = [s for s in STAGES[:position] if not state.is_done(s)]
    if missing:
        return Result.failure(
            "out_of_order",
            f"אי אפשר להריץ {name} לפני שהושלמו: {', '.join(missing)}",
            recoverable=True,
            missing=missing,
        )
    return Result.success("ready", f"שלב {name} מוכן לריצה")


def complete(state: MigrationState, name: str, detail: str = "") -> MigrationState:
    stage = state.stage(name)
    stage.status, stage.detail, stage.at = "done", detail, _now()
    return state


def mark_failed(state: MigrationState, name: str, detail: str) -> MigrationState:
    stage = state.stage(name)
    stage.status, stage.detail, stage.at = "failed", detail, _now()
    return state


def save(state: MigrationState, directory: Path) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{state.migration_id}.json"
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(state.to_dict(), fh, ensure_ascii=False, indent=2)
    return path


def load(migration_id: str, directory: Path) -> Result:
    path = directory / f"{migration_id}.json"
    if not path.exists():
        return Result.failure("migration_missing", f"לא נמצאה העברה בשם {migration_id}")
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return Result.failure(
            "migration_corrupt",
            f"קובץ מצב ההעברה פגום: {exc}. אל תמשיך — בדוק ידנית מה מצב שני האתרים.",
            recoverable=False,
        )
    state = MigrationState(
        migration_id=raw["migration_id"], source=raw.get("source", ""),
        target=raw.get("target", ""),
        stages={k: StageState(**v) for k, v in (raw.get("stages") or {}).items()},
        archive_path=raw.get("archive_path", ""),
        archive_bytes=int(raw.get("archive_bytes") or 0),
        method=raw.get("method", ""),
        import_approved=bool(raw.get("import_approved")),
        backups_released=bool(raw.get("backups_released")),
        created_at=raw.get("created_at", ""),
    )
    return Result.success("loaded", f"העברה {migration_id} נטענה", state=state)



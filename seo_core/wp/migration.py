"""
Moving a WordPress site without losing anything.
================================================

A migration is the one operation in this toolkit that can destroy a business in
an afternoon, so the design is defensive in three specific ways.

**It is a state machine on disk.** Every stage records that it happened. A run
that dies halfway can be read afterwards — what completed, what the sites look
like now, and what the way out is. Re-running never repeats a completed stage.

**Nothing irreversible happens without a verified backup on both sides.** Not a
backup that was taken: a backup that was proven restorable. And no backup is
deleted until Lior says the migration is finished.

**Pruning never touches content.** Caches, logs, transients and stale plugin
backups are fair game. Media, posts, users and orders are not, at any size. If
the archive is still over the limit after safe pruning, the run stops and shows
what is large — it does not start deleting things to fit.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable

from ..change_guard.checks import Check, CheckReport, visible_text
from ..schema import Result
from .limits import HARD_ARCHIVE_LIMIT, ServerLimits, check_archive, human

Runner = Callable[[list[str]], tuple[int, str, str]]    # argv -> (code, stdout, stderr)
Fetcher = Callable[[str], tuple[int, str]]

#: In order. Each stage may only run once its predecessors are done.
STAGES = (
    "preflight",        # what the two sites can do, and what the limits are
    "backup_source",    # full backup of the site we are moving
    "backup_target",    # full backup of whatever we are about to overwrite
    "verify_backups",   # prove both restore before anything is touched
    "export",           # build the .wpress
    "size_gate",        # the 500MB hard limit, measured on the finished file
    "import",           # write to the target — requires explicit approval
    "postcheck",        # what must be true afterwards
)

#: Safe to drop from an export. Every one of these is regenerated by WordPress
#: or by a plugin on demand.
PRUNABLE = {
    "cache":            "קבצי cache של תוספים (wp-content/cache)",
    "plugin_backups":   "גיבויים ישנים שתוספים יצרו (ai1wm-backups, updraft)",
    "transients":       "transients פגי תוקף בבסיס הנתונים",
    "logs":             "קבצי לוג ודיבאג (debug.log, error_log)",
    "revisions":        "גרסאות ישנות של פוסטים — התוכן הנוכחי לא נוגע",
    "spam_comments":    "תגובות שסומנו כספאם ובאשפה",
    "temp":             "קבצים זמניים ותיקיות upgrade",
}

#: Never, at any size. Deleting one of these to fit under a limit is how a
#: migration turns into a data loss incident.
NEVER_PRUNE = (
    "wp-content/uploads — מדיה",
    "פוסטים, דפים ותוכן",
    "משתמשים והרשאות",
    "הזמנות ומוצרים (WooCommerce)",
    "רשומות טפסים",
    "טבלאות של תוספים שלא מזוהות כ-cache",
)

#: Plugins whose licence is bound to the domain and needs re-activating after a
#: move. Not detectable from the HTML — this is the list to walk manually.
LICENCE_BOUND = (
    "Elementor Pro", "WP Rocket", "Gravity Forms", "ACF Pro",
    "WPML", "Rank Math PRO", "Yoast SEO Premium", "WooCommerce extensions",
)


